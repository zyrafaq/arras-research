const V1_MAGIC = new Uint8Array([0x6a, 0xba, 0xda, 0xb3, 0xf0]);

function padB64(s) {
    const r = s.length % 4;
    if (r === 2) return s + "==";
    if (r === 3) return s + "=";
    return s;
}

function b64Decode(s) {
    return Uint8Array.from(atob(padB64(s.replace(/ /g, ""))), c => c);
}

function b64Encode(data) {
    let s = btoa(String.fromCharCode(...data));
    while (s.endsWith("=")) s = s.slice(0, -1);
    return s;
}

function rgbToInt(r, g, b) { return (r << 16) | (g << 8) | b; }
function intToRgb(c) { return [(c >> 16) & 0xff, (c >> 8) & 0xff, c & 0xff]; }
function intToHex(c) { const [r, g, b] = intToRgb(c); return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}`; }

function decodeV1(data) {
    if (data.length < 7 || data[0] !== 0x6a || data[1] !== 0xba || data[2] !== 0xda || data[3] !== 0xb3 || data[4] !== 0xf0) {
        throw new Error("Not v1 format (bad magic)");
    }
    let off = 5;
    if (data[off] !== 1) throw new Error("Unexpected v1 version: " + data[off]);
    off++;
    const nameLen = data[off]; off++;
    const name = new TextDecoder().decode(data.slice(off, off + nameLen)); off += nameLen;
    const authorLen = data[off]; off++;
    const author = new TextDecoder().decode(data.slice(off, off + authorLen)); off += authorLen;
    const tableLen = data[off]; off++;
    const table = [];
    for (let i = 0; i < tableLen; i++) {
        table.push(rgbToInt(data[off], data[off + 1], data[off + 2]));
        off += 3;
    }
    const specialLen = data[off]; off++;
    const special = [];
    for (let i = 0; i < specialLen; i++) {
        special.push(rgbToInt(data[off], data[off + 1], data[off + 2]));
        off += 3;
    }
    const blend = data[off] / 0xff; off++;
    const neon = !!data[off]; off++;
    return { name: name || "Unknown Theme", author, table, specialTable: special, blend: Math.round(blend * 10000) / 10000, neon };
}

function decodeV0(data) {
    if (data.length >= 5 && data[0] === 0x6a && data[1] === 0xba && data[2] === 0xda && data[3] === 0xb3 && data[4] === 0xf0) {
        throw new Error("Looks like v1, not v0");
    }
    let idx = data.indexOf(0);
    if (idx === -1) throw new Error("No null terminator for name");
    const name = new TextDecoder().decode(data.slice(0, idx)).trim() || "Unknown Theme";
    data = data.slice(idx + 1);
    idx = data.indexOf(0);
    if (idx === -1) throw new Error("No null terminator for author");
    const author = new TextDecoder().decode(data.slice(0, idx)).trim();
    data = data.slice(idx + 1);
    if (data.length < 1) throw new Error("Missing blend byte");
    const blend = data[0] / 0xff;
    data = data.slice(1);
    const paletteSize = Math.floor(data.length / 3);
    if (paletteSize < 2) throw new Error("Too few colors: " + paletteSize);
    const table = [];
    for (let i = 0; i < paletteSize; i++) {
        table.push(rgbToInt(data[i * 3], data[i * 3 + 1], data[i * 3 + 2]));
    }
    return { name, author, table, specialTable: [table.length > 9 ? table[9] : table[0]], blend: Math.round(blend * 10000) / 10000, neon: false };
}

export function parseThemeCode(code) {
    code = code.trim();
    try {
        const data = b64Decode(code);
        if (data.length >= 5 && data[0] === 0x6a && data[1] === 0xba && data[2] === 0xda && data[3] === 0xb3 && data[4] === 0xf0) {
            return themeFromBinary(decodeV1(data));
        }
    } catch (e) {  }
    try {
        const data = b64Decode(code);
        return themeFromBinary(decodeV0(data));
    } catch (e) {  }
    return null;
}

function themeFromBinary(theme) {
    const content = {};
    for (let i = 0; i < theme.table.length && i < PALETTE_NAMES.length; i++) {
        content[PALETTE_NAMES[i]] = intToHex(theme.table[i]);
    }
    return {
        name: theme.name,
        author: theme.author,
        content,
        paletteSize: theme.table.length,
        border: theme.blend,
        neon: theme.neon,
    };
}

export function themeToCode(themeObj) {
    const content = themeObj.content || themeObj;
    const table = PALETTE_NAMES.map(name => {
        const hex = content[name] || "#000000";
        return parseInt(hex.slice(1), 16);
    });
    const name = (themeObj.name || "Custom").slice(0, 40);
    const author = (themeObj.author || "").slice(0, 40);
    const blend = themeObj.border != null ? themeObj.border : 0.65;
    const neon = themeObj.neon || false;
    const parts = [];
    parts.push(...V1_MAGIC);
    parts.push(1);
    const nameBytes = new TextEncoder().encode(name);
    parts.push(nameBytes.length); parts.push(...nameBytes);
    const authorBytes = new TextEncoder().encode(author);
    parts.push(authorBytes.length); parts.push(...authorBytes);
    parts.push(table.length);
    for (const c of table) { parts.push((c >> 16) & 0xff, (c >> 8) & 0xff, c & 0xff); }
    parts.push(1);
    const specialColor = table[9] || 0;
    parts.push((specialColor >> 16) & 0xff, (specialColor >> 8) & 0xff, specialColor & 0xff);
    const blendByte = blend >= 1 ? 255 : (blend <= 0 ? 0 : Math.round(blend * 255));
    parts.push(blendByte);
    parts.push(neon ? 1 : 0);
    return b64Encode(new Uint8Array(parts));
}

